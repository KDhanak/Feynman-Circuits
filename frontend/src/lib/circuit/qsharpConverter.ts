import type {
	CircuitIR,
	UnitaryOperation,
	MeasureOperation,
	ResetOperation,
	BarrierOperation,
	CircuitOperation,
	CanonicalUnitaryGate
} from '../IR/schema';
import { isParametricGate } from '../quantum/gates';
import { parseAngle } from './openQasmConverter';

export interface QSharpExportOptions {
	includeComments?: boolean;
	/** Name of the generated entry-point operation. */
	operationName?: string;
}

// Name of the qubit array in the code we generate, and of the array that
// holds measurement results. Q# has no separate classical register, so the
// IR's classical bits become one `Result[]` that the operation returns.
const QUBITS = 'qs';
const RESULTS = 'results';

// Body lines sit inside `operation Main() { ... }`. Q#'s own formatter uses
// four spaces, so generated code matches what the QDK would produce.
const INDENT = '    ';

// The Q# operation for each canonical gate. Every one of these lives in
// Microsoft.Quantum.Intrinsic, which the compiler opens automatically, so the
// generated program needs no `import` line of its own.
const QSHARP_OP: Record<CanonicalUnitaryGate, string> = {
	x: 'X',
	y: 'Y',
	z: 'Z',
	h: 'H',
	s: 'S',
	t: 'T',
	p: 'R1',
	rx: 'Rx',
	ry: 'Ry',
	rz: 'Rz',
	swap: 'SWAP'
};

// Short intrinsic names for the controlled forms that Q# gives a name of their
// own. Anything not listed here uses the general `Controlled G([...], ...)`
// functor form, which works for any number of controls.
const CONTROLLED_OP: Partial<Record<CanonicalUnitaryGate, Record<number, string>>> = {
	x: { 1: 'CNOT', 2: 'CCNOT' },
	z: { 1: 'CZ' }
};

export function circuitToQSharp(ir: CircuitIR, options: QSharpExportOptions = {}): string {
	const { includeComments = true, operationName = 'Main' } = options;

	const numQubits = ir.registers.q;
	const numClassicalBits = ir.registers.c;

	// Write the body first. Only then do we know whether any measurement
	// actually stored a result, which decides the operation's return type.
	const usedResults = { any: false };
	const body: string[] = [];

	const sortedOps = [...ir.operations].sort((a, b) => a.column - b.column);
	for (const op of sortedOps) {
		const line = operationToQSharp(op, numClassicalBits, usedResults);
		if (line) {
			body.push(line);
		}
	}

	const returnsResults = usedResults.any;

	const lines: string[] = [];
	if (includeComments) {
		lines.push('// Generated by Feynman Circuits');
	}
	lines.push(`operation ${operationName}() : ${returnsResults ? 'Result[]' : 'Unit'} {`);
	lines.push(`${INDENT}use ${QUBITS} = Qubit[${numQubits}];`);
	if (returnsResults) {
		lines.push(`${INDENT}mutable ${RESULTS} = [Zero, size = ${numClassicalBits}];`);
	}
	lines.push('');

	// Each entry may itself be several lines (an anti-controlled gate), so split
	// before indenting to keep the block lined up.
	for (const entry of body) {
		for (const line of entry.split('\n')) {
			lines.push(`${INDENT}${line}`);
		}
	}
	if (body.length > 0) {
		lines.push('');
	}

	// Q# requires every qubit to be back in |0> when it is released, so the
	// operation always resets before it returns.
	lines.push(`${INDENT}ResetAll(${QUBITS});`);
	if (returnsResults) {
		lines.push(`${INDENT}return ${RESULTS};`);
	}
	lines.push('}');

	return lines.join('\n');
}

function operationToQSharp(
	op: CircuitOperation,
	numClassicalBits: number,
	usedResults: { any: boolean }
): string | null {
	switch (op.kind) {
		case 'unitary':
			return unitaryToQSharp(op as UnitaryOperation);
		case 'measure':
			return measureToQSharp(op as MeasureOperation, numClassicalBits, usedResults);
		case 'reset':
			return `Reset(${qubit((op as ResetOperation).targets[0])});`;
		case 'barrier':
			// Q# has no barrier: it is a layout hint, not an instruction, and the
			// compiler keeps the statement order we write anyway. Leaving a comment
			// keeps the generated code lined up with the board.
			return `// barrier ${(op as BarrierOperation).targets.map(qubit).join(', ')}`;
		default:
			return null;
	}
}

function measureToQSharp(
	op: MeasureOperation,
	numClassicalBits: number,
	usedResults: { any: boolean }
): string {
	const target = qubit(op.targets[0]);
	const bit = op.classicalTargets[0] ?? 0;

	// A measurement with nowhere to put its result still has to happen, because
	// it collapses the state for everything after it. Bind it to `_` so the
	// program stays valid without inventing a classical bit.
	if (bit >= numClassicalBits) {
		return `let _ = M(${target});`;
	}

	usedResults.any = true;
	return `set ${RESULTS} w/= ${bit} <- M(${target});`;
}

function unitaryToQSharp(op: UnitaryOperation): string {
	if (op.controls.length > 0 || op.antiControls.length > 0) {
		return controlledToQSharp(op);
	}
	return `${QSHARP_OP[op.gate]}(${gateArgs(op.gate, op.targets, op.params)});`;
}

// Q# has no anti-controls, so we build them with an "X-sandwich" (the same way
// as the OpenQASM and Qiskit exporters): flip the anti-control qubit, apply the
// gate with it as a normal control, then flip it back.
function controlledToQSharp(op: UnitaryOperation): string {
	const allControls = [...op.controls, ...op.antiControls];

	const lines: string[] = [];
	for (const ac of op.antiControls) {
		lines.push(`X(${qubit(ac)});`);
	}
	lines.push(controlledInstruction(op.gate, allControls, op.targets, op.params));
	for (const ac of op.antiControls) {
		lines.push(`X(${qubit(ac)});`);
	}
	return lines.join('\n');
}

function controlledInstruction(
	gate: CanonicalUnitaryGate,
	controls: number[],
	targets: number[],
	params: number[]
): string {
	const named = CONTROLLED_OP[gate]?.[controls.length];
	if (named) {
		return `${named}(${[...controls, ...targets].map(qubit).join(', ')});`;
	}

	// The general form. `Controlled` takes the control qubits as an array and
	// the operation's own arguments as a single value, so anything other than
	// one plain target has to be wrapped in a tuple.
	const controlArray = `[${controls.map(qubit).join(', ')}]`;
	const args = gateArgs(gate, targets, params);
	const argTuple = needsTuple(gate, targets) ? `(${args})` : args;
	return `Controlled ${QSHARP_OP[gate]}(${controlArray}, ${argTuple});`;
}

function needsTuple(gate: CanonicalUnitaryGate, targets: number[]): boolean {
	return isParametricGate(gate) || targets.length > 1;
}

// The arguments the gate's own operation takes: an angle first for the
// rotations and the phase gate, then the qubit or qubits it acts on.
function gateArgs(gate: CanonicalUnitaryGate, targets: number[], params: number[]): string {
	const qubits = (gate === 'swap' ? targets.slice(0, 2) : targets.slice(0, 1)).map(qubit);
	if (isParametricGate(gate)) {
		return [formatDouble(params[0] ?? 0), ...qubits].join(', ');
	}
	return qubits.join(', ');
}

function qubit(index: number): string {
	return `${QUBITS}[${index}]`;
}

// Q# is strongly typed, and an angle is a Double. A whole number written
// plainly (`0`, `3`) would be an Int and fail to compile, so make sure every
// angle we write has a decimal point or an exponent.
function formatDouble(value: number): string {
	if (!Number.isFinite(value)) return '0.0';
	const text = String(value);
	return /[.eE]/.test(text) ? text : `${text}.0`;
}

// Q# operation name -> canonical gate, built by reversing QSHARP_OP so the two
// directions can never drift apart. Keys are lower-cased on both sides of the
// lookup, so `Rx`, `RX` and `rx` all resolve.
const OP_TO_GATE: Record<string, CanonicalUnitaryGate> = Object.fromEntries(
	Object.entries(QSHARP_OP).map(([gate, op]) => [op.toLowerCase(), gate])
) as Record<string, CanonicalUnitaryGate>;

// The named controlled intrinsics, including the ones we never emit ourselves
// (CX, CY) so that hand-written Q# still imports.
const CONTROLLED_ALIAS: Record<string, { gate: CanonicalUnitaryGate; controls: number }> = {
	cnot: { gate: 'x', controls: 1 },
	cx: { gate: 'x', controls: 1 },
	cy: { gate: 'y', controls: 1 },
	cz: { gate: 'z', controls: 1 },
	ccnot: { gate: 'x', controls: 2 },
	ccx: { gate: 'x', controls: 2 }
};

// Where each `use` declaration starts in the flat list of qubits, so both
// `use qs = Qubit[3];` and a run of `use a = Qubit();` lines can be indexed.
interface QubitScope {
	arrays: Map<string, number>;
	singles: Map<string, number>;
}

/**
 * Read Q# source and turn it back into CircuitIR.
 *
 * This reads the shape `circuitToQSharp` writes, plus the common variations of
 * it that appear in hand-written Q#. One thing does not survive the round trip:
 * an anti-control was exported as an X-sandwich, and it comes back as the three
 * plain gates it was written as. The circuit still does the same thing, it just
 * no longer shows an open circle on the board. The Qiskit importer behaves the
 * same way.
 */
export function qsharpToCircuit(qsharpCode: string): CircuitIR | null {
	try {
		// Barriers leave the exporter as comments, so look for them before the
		// comments are stripped, and keep them in place among the other statements.
		const lines: { text: string; barrier?: string }[] = [];
		for (const raw of qsharpCode.split('\n')) {
			const trimmed = raw.trim();
			const barrierMatch = trimmed.match(/^\/\/\s*barrier\s+(.+)$/i);
			if (barrierMatch) {
				lines.push({ text: '', barrier: barrierMatch[1] });
				continue;
			}
			const text = trimmed.replace(/\/\/.*$/, '').trim();
			if (text) lines.push({ text });
		}

		const scope: QubitScope = { arrays: new Map(), singles: new Map() };
		let numQubits = 0;
		let numClassicalBits = 0;

		for (const { text } of lines) {
			// `use qs = Qubit[3];`, with an optional `{` for the block form.
			const arrayMatch = text.match(/^(?:use|borrow)\s+(\w+)\s*=\s*Qubit\[\s*(\d+)\s*\]\s*[;{]?$/);
			if (arrayMatch) {
				scope.arrays.set(arrayMatch[1], numQubits);
				numQubits += parseInt(arrayMatch[2], 10);
				continue;
			}
			// `use a = Qubit();` — each one is a single qubit, numbered in order.
			const singleMatch = text.match(/^(?:use|borrow)\s+(\w+)\s*=\s*Qubit\(\s*\)\s*[;{]?$/);
			if (singleMatch) {
				scope.singles.set(singleMatch[1], numQubits);
				numQubits += 1;
				continue;
			}
			// `mutable results = [Zero, size = 2];` or the older `new Result[2]`.
			const resultsMatch = text.match(
				/^mutable\s+\w+\s*=\s*(?:\[\s*Zero\s*,\s*size\s*=\s*(\d+)\s*\]|new\s+Result\[\s*(\d+)\s*\])\s*;?$/
			);
			if (resultsMatch) {
				numClassicalBits = parseInt(resultsMatch[1] ?? resultsMatch[2], 10);
			}
		}

		if (numQubits === 0) return null;

		const operations: CircuitOperation[] = [];
		// Q# statements are a plain sequence, but the board is a grid. Give each
		// operation the first column where every qubit it touches is still free.
		const qubitNextColumn = new Array<number>(numQubits).fill(0);

		const placeOp = (op: CircuitOperation) => {
			const involved = [
				...op.targets,
				...('controls' in op ? op.controls : []),
				...('antiControls' in op ? op.antiControls : [])
			];
			const column = involved.length
				? Math.max(...involved.map((q) => qubitNextColumn[q] ?? 0))
				: 0;
			op.column = column;
			for (const q of involved) {
				qubitNextColumn[q] = column + 1;
			}
			operations.push(op);
		};

		for (const { text, barrier } of lines) {
			if (barrier !== undefined) {
				const targets = splitArgs(barrier)
					.map((a) => parseQubit(a, scope))
					.filter((q): q is number => q !== null);
				if (targets.length) {
					placeOp({
						id: crypto.randomUUID(),
						kind: 'barrier',
						gate: 'barrier',
						column: 0,
						targets
					});
				}
				continue;
			}

			for (const op of parseStatement(text, scope)) {
				placeOp(op);
			}
		}

		// A measurement can name a classical bit that no `mutable` line declared,
		// so make sure the register is big enough to hold every one of them.
		for (const op of operations) {
			if (op.kind === 'measure') {
				numClassicalBits = Math.max(numClassicalBits, (op.classicalTargets[0] ?? -1) + 1);
			}
		}

		return {
			version: '1.0',
			registers: { q: numQubits, c: numClassicalBits },
			qubitLabels: Array.from({ length: numQubits }, (_, i) => `q${i}`),
			operations
		};
	} catch {
		return null;
	}
}

// One Q# statement can produce more than one operation: MResetZ both measures
// and resets, so it comes back as the two operations the board knows about.
function parseStatement(text: string, scope: QubitScope): CircuitOperation[] {
	const statement = text.replace(/;+$/, '').trim();
	if (!statement) return [];

	// `set results w/= 0 <- M(qs[0])`
	const storedMeasure = statement.match(
		/^set\s+\w+\s+w\/=\s*(\d+)\s*<-\s*(M|MResetZ)\s*\(\s*(.+?)\s*\)$/
	);
	if (storedMeasure) {
		return measureOps(storedMeasure[3], parseInt(storedMeasure[1], 10), storedMeasure[2], scope);
	}

	// `let _ = M(qs[0])` / `mutable r = MResetZ(qs[0])`
	const boundMeasure = statement.match(
		/^(?:let|mutable)\s+\S+\s*=\s*(M|MResetZ)\s*\(\s*(.+?)\s*\)$/
	);
	if (boundMeasure) {
		return measureOps(boundMeasure[2], 0, boundMeasure[1], scope);
	}

	// `Controlled Ry([qs[0], qs[1]], (0.25, qs[2]))`
	const controlled = statement.match(/^Controlled\s+(\w+)\s*\(([\s\S]*)\)$/);
	if (controlled) {
		const args = splitArgs(controlled[2]);
		if (args.length < 2 || !args[0].startsWith('[')) return [];
		// Everything after the control array is the gate's own argument. If the
		// gate takes more than one, Q# passes them as a single tuple, so unwrap it.
		const rest = args.slice(1);
		const gateArgs =
			rest.length === 1 && rest[0].startsWith('(') ? splitArgs(unwrap(rest[0])) : rest;
		return parseControlled(controlled[1], splitArgs(unwrap(args[0])), gateArgs, scope);
	}

	// Any other call: `H(qs[0])`, `CNOT(qs[0], qs[1])`, `Reset(qs[0])`, ...
	const call = statement.match(/^(\w+)\s*\((.*)\)$/);
	if (!call) return [];
	return parseCall(call[1], call[2], scope);
}

function parseCall(name: string, argsStr: string, scope: QubitScope): CircuitOperation[] {
	const key = name.toLowerCase();
	const args = splitArgs(argsStr);

	// ResetAll is the cleanup the exporter always adds before returning, not
	// something the user put on the board, so it is dropped on the way back in.
	if (key === 'resetall') return [];

	if (key === 'reset' && args.length === 1) {
		const q = parseQubit(args[0], scope);
		if (q === null) return [];
		return [{ id: crypto.randomUUID(), kind: 'reset', gate: 'reset', column: 0, targets: [q] }];
	}

	if ((key === 'm' || key === 'mresetz') && args.length === 1) {
		return measureOps(args[0], 0, key, scope);
	}

	const alias = CONTROLLED_ALIAS[key];
	if (alias && args.length === alias.controls + 1) {
		const qubits = args.map((a) => parseQubit(a, scope));
		if (qubits.some((q) => q === null)) return [];
		const controls = (qubits as number[]).slice(0, alias.controls);
		const targets = (qubits as number[]).slice(alias.controls);
		return [makeUnitary(alias.gate, targets, controls, [])];
	}

	const gate = OP_TO_GATE[key];
	if (!gate) return [];

	const parsed = parseGateArgs(gate, args, scope);
	return parsed ? [makeUnitary(gate, parsed.targets, [], parsed.params)] : [];
}

function parseControlled(
	name: string,
	controlArgs: string[],
	gateArgs: string[],
	scope: QubitScope
): CircuitOperation[] {
	const gate = OP_TO_GATE[name.toLowerCase()];
	if (!gate) return [];

	const controls = controlArgs.map((a) => parseQubit(a, scope));
	if (controls.length === 0 || controls.some((q) => q === null)) return [];

	const parsed = parseGateArgs(gate, gateArgs, scope);
	if (!parsed) return [];

	return [makeUnitary(gate, parsed.targets, controls as number[], parsed.params)];
}

// Splits a gate's own arguments into the leading angle (if it takes one) and
// the qubits it acts on, checking the count matches what the gate expects.
function parseGateArgs(
	gate: CanonicalUnitaryGate,
	args: string[],
	scope: QubitScope
): { targets: number[]; params: number[] } | null {
	const params: number[] = [];
	let qubitArgs = args;

	if (isParametricGate(gate)) {
		if (args.length < 2) return null;
		const angle = parseQSharpAngle(args[0]);
		if (angle === null) return null;
		params.push(angle);
		qubitArgs = args.slice(1);
	}

	const expected = gate === 'swap' ? 2 : 1;
	if (qubitArgs.length !== expected) return null;

	const targets = qubitArgs.map((a) => parseQubit(a, scope));
	if (targets.some((q) => q === null)) return null;

	return { targets: targets as number[], params };
}

function measureOps(
	qubitArg: string,
	classicalBit: number,
	op: string,
	scope: QubitScope
): CircuitOperation[] {
	const q = parseQubit(qubitArg, scope);
	if (q === null) return [];

	const ops: CircuitOperation[] = [
		{
			id: crypto.randomUUID(),
			kind: 'measure',
			gate: 'measure',
			column: 0,
			targets: [q],
			classicalTargets: [classicalBit]
		}
	];
	// MResetZ measures and then puts the qubit back in |0>, which is two
	// separate things on the board.
	if (op.toLowerCase() === 'mresetz') {
		ops.push({ id: crypto.randomUUID(), kind: 'reset', gate: 'reset', column: 0, targets: [q] });
	}
	return ops;
}

function makeUnitary(
	gate: CanonicalUnitaryGate,
	targets: number[],
	controls: number[],
	params: number[]
): UnitaryOperation {
	return {
		id: crypto.randomUUID(),
		kind: 'unitary',
		gate,
		column: 0,
		targets,
		controls,
		antiControls: [],
		params
	};
}

// Turns a qubit argument into a plain number. Accepts an element of a declared
// array (`qs[2]`) or the name of a single declared qubit (`control`).
function parseQubit(arg: string, scope: QubitScope): number | null {
	const token = arg.trim();

	const indexed = token.match(/^(\w+)\s*\[\s*(\d+)\s*\]$/);
	if (indexed) {
		const base = scope.arrays.get(indexed[1]);
		if (base === undefined) return null;
		return base + parseInt(indexed[2], 10);
	}

	const single = scope.singles.get(token);
	return single === undefined ? null : single;
}

// Accepts plain doubles, and pi expressions written the Q# way (`PI()`,
// `PI()/2.0`) with or without a namespace in front of them.
function parseQSharpAngle(arg: string): number | null {
	const normalized = arg
		.replace(/\b(?:Std|Microsoft)\.Quantum\.Math\.|\bStd\.Math\./g, '')
		.replace(/\bPI\s*\(\s*\)/gi, 'pi')
		// Q# writes every whole number in a Double expression with a decimal
		// point (`PI()/2.0`), which `parseAngle` does not expect in a divisor.
		// Dropping a trailing `.0` leaves the value alone and lets it match.
		.replace(/(\d)\.0+\b/g, '$1')
		.trim();
	const value = parseAngle(normalized);
	return Number.isFinite(value) ? value : null;
}

// Removes one layer of surrounding brackets or parentheses: `[a, b]` -> `a, b`.
function unwrap(text: string): string {
	return text.trim().replace(/^[[(]([\s\S]*)[\])]$/, '$1');
}

// Splits an argument list on the commas that separate the arguments, ignoring
// the ones nested inside a qubit index or a tuple. A plain `split(',')` would
// cut `[qs[0], qs[1]]` in the wrong places.
function splitArgs(argsStr: string): string[] {
	const parts: string[] = [];
	let depth = 0;
	let current = '';

	for (const char of argsStr) {
		if (char === '(' || char === '[') depth += 1;
		else if (char === ')' || char === ']') depth -= 1;

		if (char === ',' && depth === 0) {
			parts.push(current.trim());
			current = '';
			continue;
		}
		current += char;
	}
	parts.push(current.trim());

	return parts.filter((part) => part.length > 0);
}
