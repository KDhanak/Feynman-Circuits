import type { CircuitIR, UnitaryOperation, MeasureOperation, ResetOperation, BarrierOperation, CircuitOperation } from '../IR/schema';

export interface OpenQasmExportOptions {
	version?: '2.0' | '3.0';
	includeComments?: boolean;
}

export function circuitToOpenQasm(ir: CircuitIR, options: OpenQasmExportOptions = {}): string {
	const { version = '3.0', includeComments = true } = options;

	if (version === '2.0') {
		return circuitToOpenQasm2(ir, includeComments);
	} else {
		return circuitToOpenQasm3(ir, includeComments);
	}
}

function circuitToOpenQasm3(ir: CircuitIR, includeComments: boolean): string {
	const lines: string[] = [];

	lines.push('OPENQASM 3.0;');
	if (includeComments) {
		lines.push('// Generated by Feynman Circuits');
	}
	lines.push('');

	// Import necessary modules
	lines.push('import stdlib;');
	lines.push('');

	// Declare quantum and classical registers
	const numQubits = ir.registers.q;
	const numClassicalBits = ir.registers.c;

	lines.push(`qubit[${numQubits}] q;`);
	if (numClassicalBits > 0) {
		lines.push(`bit[${numClassicalBits}] c;`);
	}
	lines.push('');

	// Process operations sorted by column (time step)
	const sortedOps = [...ir.operations].sort((a, b) => a.column - b.column);
	for (const op of sortedOps) {
		const qasmLine = operationToOpenQasm3(op);
		if (qasmLine) {
			lines.push(qasmLine);
		}
	}

	return lines.join('\n');
}

function circuitToOpenQasm2(ir: CircuitIR, includeComments: boolean): string {
	const lines: string[] = [];

	lines.push('OPENQASM 2.0;');
	if (includeComments) {
		lines.push('// Generated by Feynman Circuits');
	}
	lines.push("include \"qelib1.inc\";");
	lines.push('');

	// Declare quantum and classical registers
	const numQubits = ir.registers.q;
	const numClassicalBits = ir.registers.c;

	lines.push(`qreg q[${numQubits}];`);
	if (numClassicalBits > 0) {
		lines.push(`creg c[${numClassicalBits}];`);
	}
	lines.push('');

	// Process operations sorted by column (time step)
	const sortedOps = [...ir.operations].sort((a, b) => a.column - b.column);
	for (const op of sortedOps) {
		const qasmLine = operationToOpenQasm2(op);
		if (qasmLine) {
			lines.push(qasmLine);
		}
	}

	return lines.join('\n');
}

function operationToOpenQasm3(op: CircuitOperation): string | null {
	switch (op.kind) {
		case 'unitary':
			return unitaryToOpenQasm3(op as UnitaryOperation);
		case 'measure':
			return measureToOpenQasm3(op as MeasureOperation);
		case 'reset':
			return resetToOpenQasm3(op as ResetOperation);
		case 'barrier':
			return barrierToOpenQasm3(op as BarrierOperation);
		default:
			return null;
	}
}

function operationToOpenQasm2(op: CircuitOperation): string | null {
	switch (op.kind) {
		case 'unitary':
			return unitaryToOpenQasm2(op as UnitaryOperation);
		case 'measure':
			return measureToOpenQasm2(op as MeasureOperation);
		case 'reset':
			return resetToOpenQasm2(op as ResetOperation);
		case 'barrier':
			return barrierToOpenQasm2(op as BarrierOperation);
		default:
			return null;
	}
}

function unitaryToOpenQasm3(op: UnitaryOperation): string {
	const target = op.targets[0];
	const gate = op.gate;

	let instruction = '';

	// Handle controlled gates
	if (op.controls.length > 0 || op.antiControls.length > 0) {
		instruction = generateControlledGate3(op);
	} else {
		// Single qubit gates
		if (['rx', 'ry', 'rz'].includes(gate)) {
			const angle = op.params[0] ?? 0;
			instruction = `${gate}(${angle}) q[${target}];`;
		} else {
			instruction = `${gate} q[${target}];`;
		}
	}

	return instruction;
}

function unitaryToOpenQasm2(op: UnitaryOperation): string {
	const target = op.targets[0];
	const gate = op.gate;

	let instruction = '';

	// Handle controlled gates
	if (op.controls.length > 0 || op.antiControls.length > 0) {
		instruction = generateControlledGate2(op);
	} else {
		// Single qubit gates
		if (['rx', 'ry', 'rz'].includes(gate)) {
			const angle = op.params[0] ?? 0;
			instruction = `${gate}(${angle}) q[${target}];`;
		} else {
			instruction = `${gate} q[${target}];`;
		}
	}

	return instruction;
}

function generateControlledGate3(op: UnitaryOperation): string {
	const target = op.targets[0];
	const gate = op.gate;
	const controls = op.controls;
	const antiControls = op.antiControls;

	// Handle positive controls
	if (controls.length > 0 && antiControls.length === 0) {
		if (controls.length === 1) {
			const control = controls[0];
			if (['rx', 'ry', 'rz'].includes(gate)) {
				const angle = op.params[0] ?? 0;
				return `ctrl @ ${gate}(${angle}) q[${control}], q[${target}];`;
			} else {
				return `ctrl @ ${gate} q[${control}], q[${target}];`;
			}
		} else if (controls.length === 2) {
			const control1 = controls[0];
			const control2 = controls[1];
			if (['rx', 'ry', 'rz'].includes(gate)) {
				const angle = op.params[0] ?? 0;
				return `ctrl @ ctrl @ ${gate}(${angle}) q[${control1}], q[${control2}], q[${target}];`;
			} else {
				return `ctrl @ ctrl @ ${gate} q[${control1}], q[${control2}], q[${target}];`;
			}
		}
	}

	// Fallback to uncontrolled gate
	if (['rx', 'ry', 'rz'].includes(gate)) {
		const angle = op.params[0] ?? 0;
		return `${gate}(${angle}) q[${target}];`;
	} else {
		return `${gate} q[${target}];`;
	}
}

function generateControlledGate2(op: UnitaryOperation): string {
	const target = op.targets[0];
	const gate = op.gate;
	const controls = op.controls;
	const antiControls = op.antiControls;

	// Handle positive controls in OpenQasm 2.0
	if (controls.length > 0 && antiControls.length === 0) {
		if (controls.length === 1) {
			const control = controls[0];
			if (gate === 'x') {
				return `cx q[${control}], q[${target}];`;
			} else if (gate === 'z') {
				return `cz q[${control}], q[${target}];`;
			} else if (['rx', 'ry', 'rz'].includes(gate)) {
				const angle = op.params[0] ?? 0;
				return `c${gate}(${angle}) q[${control}], q[${target}];`;
			} else {
				return `c${gate} q[${control}], q[${target}];`;
			}
		} else if (controls.length === 2) {
			const control1 = controls[0];
			const control2 = controls[1];
			if (gate === 'x') {
				return `ccx q[${control1}], q[${control2}], q[${target}];`;
			}
		}
	}

	// Fallback to uncontrolled gate
	if (['rx', 'ry', 'rz'].includes(gate)) {
		const angle = op.params[0] ?? 0;
		return `${gate}(${angle}) q[${target}];`;
	} else {
		return `${gate} q[${target}];`;
	}
}

function measureToOpenQasm3(op: MeasureOperation): string {
	const qubit = op.targets[0];
	const classicalBit = op.classicalTargets[0] ?? 0;
	return `measure q[${qubit}] -> c[${classicalBit}];`;
}

function measureToOpenQasm2(op: MeasureOperation): string {
	const qubit = op.targets[0];
	const classicalBit = op.classicalTargets[0] ?? 0;
	return `measure q[${qubit}] -> c[${classicalBit}];`;
}

function resetToOpenQasm3(op: ResetOperation): string {
	const qubit = op.targets[0];
	return `reset q[${qubit}];`;
}

function resetToOpenQasm2(op: ResetOperation): string {
	const qubit = op.targets[0];
	return `reset q[${qubit}];`;
}

function barrierToOpenQasm3(op: BarrierOperation): string {
	const qubits = op.targets.map(q => `q[${q}]`).join(', ');
	return `barrier ${qubits};`;
}

function barrierToOpenQasm2(op: BarrierOperation): string {
	const qubits = op.targets.map(q => `q[${q}]`).join(', ');
	return `barrier ${qubits};`;
}

// Parse OpenQasm back to CircuitIR
export function openQasmToCircuit(qasmCode: string): CircuitIR | null {
	try {
		const lines = qasmCode.split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('//'));

		let numQubits = 0;
		let numClassicalBits = 0;
		const operations: CircuitOperation[] = [];
		const columnMap = new Map<number, number>(); // Track which column each qubit is at

		// Parse register declarations (both OpenQASM 2.0 and 3.0)
		for (const line of lines) {
			// OpenQASM 3.0: qubit[n] q;
			const qubit3Match = line.match(/qubit\[(\d+)\]\s+q/);
			if (qubit3Match) {
				numQubits = parseInt(qubit3Match[1], 10);
			}

			// OpenQASM 2.0: qreg q[n];
			const qregMatch = line.match(/qreg\s+q\[(\d+)\]/);
			if (qregMatch) {
				numQubits = parseInt(qregMatch[1], 10);
			}

			// Classical bits: bit[n] c; or creg c[n];
			const bitMatch = line.match(/bit\[(\d+)\]|creg\s+c\[(\d+)\]/);
			if (bitMatch) {
				numClassicalBits = parseInt(bitMatch[1] || bitMatch[2], 10);
			}
		}

		if (numQubits === 0) return null;

		// Parse gate operations
		let currentColumn = 0;
		for (const line of lines) {
			// Skip headers, imports, and declarations
			if (
				line.includes('OPENQASM') ||
				line.includes('include') ||
				line.includes('import') ||
				line.includes('qubit[') ||
				line.includes('qreg') ||
				line.includes('bit[') ||
				line.includes('creg') ||
				line.startsWith('//')
			) {
				continue;
			}

			// Skip empty lines
			if (!line || line.length === 0) continue;

			const gateOp = parseGateLine(line, currentColumn);
			if (gateOp) {
				operations.push(gateOp);
				// Update column for next gate
				if ('targets' in gateOp) {
					const maxQubit = Math.max(
						...(gateOp.targets as number[]),
						...('controls' in gateOp ? (gateOp.controls as number[]) : []),
						...('antiControls' in gateOp ? (gateOp.antiControls as number[]) : [])
					);
					if (!columnMap.has(maxQubit)) {
						columnMap.set(maxQubit, 0);
					}
					columnMap.set(maxQubit, (columnMap.get(maxQubit) ?? 0) + 1);
					currentColumn = Math.max(...Array.from(columnMap.values()));
				}
			}
		}

		return {
			version: '1.0',
			registers: { q: numQubits, c: numClassicalBits },
			qubitLabels: Array.from({ length: numQubits }, (_, i) => `q${i}`),
			operations
		};
	} catch {
		return null;
	}
}

function parseGateLine(line: string, column: number): CircuitOperation | null {
	// Single qubit gates: h q[0]; or H q[0];
	const singleQubitMatch = line.match(/^([hxyzst])\s+q\[(\d+)\];?$/i);
	if (singleQubitMatch) {
		const gate = singleQubitMatch[1].toLowerCase();
		const target = parseInt(singleQubitMatch[2], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'unitary',
			gate: gate as any,
			column,
			targets: [target],
			controls: [],
			antiControls: [],
			params: []
		};
	}

	// Parametric gates: rx(1.57) q[0]; or rx(pi/2) q[0];
	const paramGateMatch = line.match(/^(rx|ry|rz)\s*\(([^)]+)\)\s+q\[(\d+)\];?$/i);
	if (paramGateMatch) {
		const gate = paramGateMatch[1].toLowerCase();
		let angle = parseAngle(paramGateMatch[2]);
		const target = parseInt(paramGateMatch[3], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'unitary',
			gate: gate as any,
			column,
			targets: [target],
			controls: [],
			antiControls: [],
			params: [angle]
		};
	}

	// CNOT/CX: cx q[0], q[1]; or CX q[0], q[1];
	const cxMatch = line.match(/^cx\s+q\[(\d+)\]\s*,\s*q\[(\d+)\];?$/i);
	if (cxMatch) {
		const control = parseInt(cxMatch[1], 10);
		const target = parseInt(cxMatch[2], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'unitary',
			gate: 'x',
			column,
			targets: [target],
			controls: [control],
			antiControls: [],
			params: []
		};
	}

	// CZ: cz q[0], q[1];
	const czMatch = line.match(/^cz\s+q\[(\d+)\]\s*,\s*q\[(\d+)\];?$/i);
	if (czMatch) {
		const control = parseInt(czMatch[1], 10);
		const target = parseInt(czMatch[2], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'unitary',
			gate: 'z',
			column,
			targets: [target],
			controls: [control],
			antiControls: [],
			params: []
		};
	}

	// Toffoli/CCX: ccx q[0], q[1], q[2];
	const ccxMatch = line.match(/^ccx\s+q\[(\d+)\]\s*,\s*q\[(\d+)\]\s*,\s*q\[(\d+)\];?$/i);
	if (ccxMatch) {
		const control1 = parseInt(ccxMatch[1], 10);
		const control2 = parseInt(ccxMatch[2], 10);
		const target = parseInt(ccxMatch[3], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'unitary',
			gate: 'x',
			column,
			targets: [target],
			controls: [control1, control2],
			antiControls: [],
			params: []
		};
	}

	// Measurement: measure q[0] -> c[0];
	const measureMatch = line.match(/^measure\s+q\[(\d+)\]\s*->\s*c\[(\d+)\];?$/i);
	if (measureMatch) {
		const qubit = parseInt(measureMatch[1], 10);
		const classicalBit = parseInt(measureMatch[2], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'measure',
			gate: 'measure',
			column,
			targets: [qubit],
			classicalTargets: [classicalBit]
		};
	}

	// Barrier: barrier q[0], q[1];
	const barrierMatch = line.match(/^barrier\s+(.+);?$/i);
	if (barrierMatch) {
		const qubits = (barrierMatch[1].match(/\d+/g) || []).map(Number);
		return {
			id: crypto.randomUUID(),
			kind: 'barrier',
			gate: 'barrier',
			column,
			targets: qubits
		};
	}

	// Reset: reset q[0];
	const resetMatch = line.match(/^reset\s+q\[(\d+)\];?$/i);
	if (resetMatch) {
		const qubit = parseInt(resetMatch[1], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'reset',
			gate: 'reset',
			column,
			targets: [qubit]
		};
	}

	return null;
}

function parseAngle(angleStr: string): number {
	// Handle common expressions
	if (angleStr.includes('pi')) {
		const piMatch = angleStr.match(/(\d*\.?\d*)\s*\*?\s*pi\s*\/\s*(\d+)/);
		if (piMatch) {
			const numerator = piMatch[1] ? parseFloat(piMatch[1]) : 1;
			const denominator = parseInt(piMatch[2], 10);
			return (numerator * Math.PI) / denominator;
		}
		const simplePi = angleStr.match(/^pi$/i);
		if (simplePi) return Math.PI;
	}
	return parseFloat(angleStr);
}
