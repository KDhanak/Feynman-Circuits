import type { CircuitIR, UnitaryOperation, MeasureOperation, ResetOperation, BarrierOperation, CircuitOperation } from '../IR/schema';
import { isParametricGate, controlledQasmName } from '../quantum/gates';

export interface OpenQasmExportOptions {
	version?: '2.0' | '3.0';
	includeComments?: boolean;
}

type QasmVersion = '2.0' | '3.0';

export function circuitToOpenQasm(ir: CircuitIR, options: OpenQasmExportOptions = {}): string {
	const { version = '3.0', includeComments = true } = options;
	const lines: string[] = [];

	lines.push(version === '2.0' ? 'OPENQASM 2.0;' : 'OPENQASM 3.0;');
	if (includeComments) {
		lines.push('// Generated by Feynman Circuits');
	}
	lines.push(version === '2.0' ? 'include "qelib1.inc";' : 'import stdlib;');
	lines.push('');

	// Declare quantum and classical registers
	const numQubits = ir.registers.q;
	const numClassicalBits = ir.registers.c;

	lines.push(version === '2.0' ? `qreg q[${numQubits}];` : `qubit[${numQubits}] q;`);
	if (numClassicalBits > 0) {
		lines.push(version === '2.0' ? `creg c[${numClassicalBits}];` : `bit[${numClassicalBits}] c;`);
	}
	lines.push('');

	// Process operations sorted by column (time step)
	const sortedOps = [...ir.operations].sort((a, b) => a.column - b.column);
	for (const op of sortedOps) {
		const qasmLine = operationToOpenQasm(op, version);
		if (qasmLine) {
			lines.push(qasmLine);
		}
	}

	return lines.join('\n');
}

function operationToOpenQasm(op: CircuitOperation, version: QasmVersion): string | null {
	switch (op.kind) {
		case 'unitary':
			return unitaryToOpenQasm(op as UnitaryOperation, version);
		case 'measure':
			return measureToOpenQasm(op as MeasureOperation);
		case 'reset':
			return resetToOpenQasm(op as ResetOperation);
		case 'barrier':
			return barrierToOpenQasm(op as BarrierOperation);
		default:
			return null;
	}
}

function unitaryToOpenQasm(op: UnitaryOperation, version: QasmVersion): string {
	const target = op.targets[0];
	const gate = op.gate;

	if (op.controls.length > 0 || op.antiControls.length > 0) {
		return generateControlledGate(op, version);
	}

	if (gate === 'swap') {
		const t0 = op.targets[0];
		const t1 = op.targets[1];
		return `swap q[${t0}], q[${t1}];`;
	}

	// Single qubit gates
	if (isParametricGate(gate)) {
		const angle = op.params[0] ?? 0;
		return `${gate}(${angle}) q[${target}];`;
	}
	return `${gate} q[${target}];`;
}

// Builds the controlled-gate instruction for `numControls` positive controls
// (anti-controls are handled separately by an X-sandwich in generateControlledGate).
function controlledInstruction(
	gate: UnitaryOperation['gate'],
	controls: number[],
	target: number,
	params: number[],
	version: QasmVersion
): string {
	const qubits = [...controls, target].map((q) => `q[${q}]`).join(', ');

	if (version === '3.0') {
		const ctrlPrefix = controls.map(() => 'ctrl @').join(' ');
		if (isParametricGate(gate)) {
			const angle = params[0] ?? 0;
			return `${ctrlPrefix} ${gate}(${angle}) ${qubits};`;
		}
		return `${ctrlPrefix} ${gate} ${qubits};`;
	}

	// OpenQASM 2.0
	const ctrlName = controlledQasmName(gate, controls.length);
	if (ctrlName) {
		return `${ctrlName} ${qubits};`;
	}
	const prefix = controls.length === 1 ? 'c' : 'cc';
	if (isParametricGate(gate)) {
		const angle = params[0] ?? 0;
		return `${prefix}${gate}(${angle}) ${qubits};`;
	}
	return `${prefix}${gate} ${qubits};`;
}

// Anti-controls aren't natively expressible in OpenQASM, so they're implemented
// via an X-sandwich: flip the anti-control qubit, apply the gate with it as a
// positive control, then flip it back.
function generateControlledGate(op: UnitaryOperation, version: QasmVersion): string {
	const target = op.targets[0];
	const gate = op.gate;
	const allControls = [...op.controls, ...op.antiControls];

	if (allControls.length > 2) {
		return `// unsupported: gate "${gate}" with more than 2 controls/anti-controls`;
	}

	const lines: string[] = [];
	for (const ac of op.antiControls) {
		lines.push(`x q[${ac}];`);
	}
	lines.push(controlledInstruction(gate, allControls, target, op.params, version));
	for (const ac of op.antiControls) {
		lines.push(`x q[${ac}];`);
	}
	return lines.join('\n');
}

function measureToOpenQasm(op: MeasureOperation): string {
	const qubit = op.targets[0];
	const classicalBit = op.classicalTargets[0] ?? 0;
	return `measure q[${qubit}] -> c[${classicalBit}];`;
}

function resetToOpenQasm(op: ResetOperation): string {
	const qubit = op.targets[0];
	return `reset q[${qubit}];`;
}

function barrierToOpenQasm(op: BarrierOperation): string {
	const qubits = op.targets.map((q) => `q[${q}]`).join(', ');
	return `barrier ${qubits};`;
}

// Parse OpenQasm back to CircuitIR
export function openQasmToCircuit(qasmCode: string): CircuitIR | null {
	try {
		const lines = qasmCode.split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('//'));

		let numQubits = 0;
		let numClassicalBits = 0;
		const operations: CircuitOperation[] = [];
		const columnMap = new Map<number, number>(); // Track which column each qubit is at

		// Parse register declarations (both OpenQASM 2.0 and 3.0)
		for (const line of lines) {
			// OpenQASM 3.0: qubit[n] q;
			const qubit3Match = line.match(/qubit\[(\d+)\]\s+q/);
			if (qubit3Match) {
				numQubits = parseInt(qubit3Match[1], 10);
			}

			// OpenQASM 2.0: qreg q[n];
			const qregMatch = line.match(/qreg\s+q\[(\d+)\]/);
			if (qregMatch) {
				numQubits = parseInt(qregMatch[1], 10);
			}

			// Classical bits: bit[n] c; or creg c[n];
			const bitMatch = line.match(/bit\[(\d+)\]|creg\s+c\[(\d+)\]/);
			if (bitMatch) {
				numClassicalBits = parseInt(bitMatch[1] || bitMatch[2], 10);
			}
		}

		if (numQubits === 0) return null;

		// Parse gate operations
		let currentColumn = 0;
		for (const line of lines) {
			// Skip headers, imports, and declarations
			if (
				line.includes('OPENQASM') ||
				line.includes('include') ||
				line.includes('import') ||
				line.includes('qubit[') ||
				line.includes('qreg') ||
				line.includes('bit[') ||
				line.includes('creg') ||
				line.startsWith('//')
			) {
				continue;
			}

			// Skip empty lines
			if (!line || line.length === 0) continue;

			const gateOp = parseGateLine(line, currentColumn);
			if (gateOp) {
				operations.push(gateOp);
				// Update column for next gate
				if ('targets' in gateOp) {
					const maxQubit = Math.max(
						...(gateOp.targets as number[]),
						...('controls' in gateOp ? (gateOp.controls as number[]) : []),
						...('antiControls' in gateOp ? (gateOp.antiControls as number[]) : [])
					);
					if (!columnMap.has(maxQubit)) {
						columnMap.set(maxQubit, 0);
					}
					columnMap.set(maxQubit, (columnMap.get(maxQubit) ?? 0) + 1);
					currentColumn = Math.max(...Array.from(columnMap.values()));
				}
			}
		}

		return {
			version: '1.0',
			registers: { q: numQubits, c: numClassicalBits },
			qubitLabels: Array.from({ length: numQubits }, (_, i) => `q${i}`),
			operations
		};
	} catch {
		return null;
	}
}

function parseGateLine(line: string, column: number): CircuitOperation | null {
	// Single qubit gates: h q[0]; or H q[0];
	const singleQubitMatch = line.match(/^([hxyzst])\s+q\[(\d+)\];?$/i);
	if (singleQubitMatch) {
		const gate = singleQubitMatch[1].toLowerCase();
		const target = parseInt(singleQubitMatch[2], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'unitary',
			gate: gate as any,
			column,
			targets: [target],
			controls: [],
			antiControls: [],
			params: []
		};
	}

	// Parametric gates: rx(1.57) q[0]; or rx(pi/2) q[0];
	const paramGateMatch = line.match(/^(rx|ry|rz)\s*\(([^)]+)\)\s+q\[(\d+)\];?$/i);
	if (paramGateMatch) {
		const gate = paramGateMatch[1].toLowerCase();
		let angle = parseAngle(paramGateMatch[2]);
		const target = parseInt(paramGateMatch[3], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'unitary',
			gate: gate as any,
			column,
			targets: [target],
			controls: [],
			antiControls: [],
			params: [angle]
		};
	}

	// Controlled parametric gates OpenQASM 2.0: crx(1.57) q[0], q[1];
	const cParamGateMatch = line.match(/^c(rx|ry|rz)\s*\(([^)]+)\)\s+q\[(\d+)\]\s*,\s*q\[(\d+)\];?$/i);
	if (cParamGateMatch) {
		const gate = cParamGateMatch[1].toLowerCase();
		const angle = parseAngle(cParamGateMatch[2]);
		const control = parseInt(cParamGateMatch[3], 10);
		const target = parseInt(cParamGateMatch[4], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'unitary',
			gate: gate as any,
			column,
			targets: [target],
			controls: [control],
			antiControls: [],
			params: [angle]
		};
	}

	// Controlled parametric gates OpenQASM 3.0: ctrl @ rx(1.57) q[0], q[1];
	const ctrlParamMatch = line.match(/^ctrl\s*@\s*(rx|ry|rz)\s*\(([^)]+)\)\s+q\[(\d+)\]\s*,\s*q\[(\d+)\];?$/i);
	if (ctrlParamMatch) {
		const gate = ctrlParamMatch[1].toLowerCase();
		const angle = parseAngle(ctrlParamMatch[2]);
		const control = parseInt(ctrlParamMatch[3], 10);
		const target = parseInt(ctrlParamMatch[4], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'unitary',
			gate: gate as any,
			column,
			targets: [target],
			controls: [control],
			antiControls: [],
			params: [angle]
		};
	}

	// Double-controlled parametric gates OpenQASM 3.0: ctrl @ ctrl @ rx(1.57) q[0], q[1], q[2];
	const ctrlCtrlParamMatch = line.match(/^ctrl\s*@\s*ctrl\s*@\s*(rx|ry|rz)\s*\(([^)]+)\)\s+q\[(\d+)\]\s*,\s*q\[(\d+)\]\s*,\s*q\[(\d+)\];?$/i);
	if (ctrlCtrlParamMatch) {
		const gate = ctrlCtrlParamMatch[1].toLowerCase();
		const angle = parseAngle(ctrlCtrlParamMatch[2]);
		const control1 = parseInt(ctrlCtrlParamMatch[3], 10);
		const control2 = parseInt(ctrlCtrlParamMatch[4], 10);
		const target = parseInt(ctrlCtrlParamMatch[5], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'unitary',
			gate: gate as any,
			column,
			targets: [target],
			controls: [control1, control2],
			antiControls: [],
			params: [angle]
		};
	}

	// CNOT/CX: cx q[0], q[1]; or CX q[0], q[1];
	const cxMatch = line.match(/^cx\s+q\[(\d+)\]\s*,\s*q\[(\d+)\];?$/i);
	if (cxMatch) {
		const control = parseInt(cxMatch[1], 10);
		const target = parseInt(cxMatch[2], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'unitary',
			gate: 'x',
			column,
			targets: [target],
			controls: [control],
			antiControls: [],
			params: []
		};
	}

	// CZ: cz q[0], q[1];
	const czMatch = line.match(/^cz\s+q\[(\d+)\]\s*,\s*q\[(\d+)\];?$/i);
	if (czMatch) {
		const control = parseInt(czMatch[1], 10);
		const target = parseInt(czMatch[2], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'unitary',
			gate: 'z',
			column,
			targets: [target],
			controls: [control],
			antiControls: [],
			params: []
		};
	}

	// Toffoli/CCX: ccx q[0], q[1], q[2];
	const ccxMatch = line.match(/^ccx\s+q\[(\d+)\]\s*,\s*q\[(\d+)\]\s*,\s*q\[(\d+)\];?$/i);
	if (ccxMatch) {
		const control1 = parseInt(ccxMatch[1], 10);
		const control2 = parseInt(ccxMatch[2], 10);
		const target = parseInt(ccxMatch[3], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'unitary',
			gate: 'x',
			column,
			targets: [target],
			controls: [control1, control2],
			antiControls: [],
			params: []
		};
	}

	// SWAP: swap q[0], q[1];
	const swapMatch = line.match(/^swap\s+q\[(\d+)\]\s*,\s*q\[(\d+)\];?$/i);
	if (swapMatch) {
		const t0 = parseInt(swapMatch[1], 10);
		const t1 = parseInt(swapMatch[2], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'unitary',
			gate: 'swap',
			column,
			targets: [t0, t1],
			controls: [],
			antiControls: [],
			params: []
		};
	}

	// Measurement: measure q[0] -> c[0];
	const measureMatch = line.match(/^measure\s+q\[(\d+)\]\s*->\s*c\[(\d+)\];?$/i);
	if (measureMatch) {
		const qubit = parseInt(measureMatch[1], 10);
		const classicalBit = parseInt(measureMatch[2], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'measure',
			gate: 'measure',
			column,
			targets: [qubit],
			classicalTargets: [classicalBit]
		};
	}

	// Barrier: barrier q[0], q[1];
	const barrierMatch = line.match(/^barrier\s+(.+);?$/i);
	if (barrierMatch) {
		const qubits = (barrierMatch[1].match(/\d+/g) || []).map(Number);
		return {
			id: crypto.randomUUID(),
			kind: 'barrier',
			gate: 'barrier',
			column,
			targets: qubits
		};
	}

	// Reset: reset q[0];
	const resetMatch = line.match(/^reset\s+q\[(\d+)\];?$/i);
	if (resetMatch) {
		const qubit = parseInt(resetMatch[1], 10);
		return {
			id: crypto.randomUUID(),
			kind: 'reset',
			gate: 'reset',
			column,
			targets: [qubit]
		};
	}

	return null;
}

function parseAngle(angleStr: string): number {
	const s = angleStr.trim();
	if (!s.includes('pi')) return parseFloat(s);

	// pi/n, n*pi/m, -pi/n, -n*pi/m
	const fracMatch = s.match(/^(-?\d*\.?\d*)\s*\*?\s*pi\s*\/\s*(-?\d+)$/i);
	if (fracMatch) {
		const coeffStr = fracMatch[1];
		const numerator = coeffStr === '' ? 1 : coeffStr === '-' ? -1 : parseFloat(coeffStr);
		const denominator = parseInt(fracMatch[2], 10);
		return (numerator * Math.PI) / denominator;
	}

	// n*pi, pi*n, -n*pi, pi*-n, 2*pi, pi*2
	const mulMatch = s.match(/^(-?\d*\.?\d*)\s*\*\s*pi$|^pi\s*\*\s*(-?\d*\.?\d*)$/i);
	if (mulMatch) {
		const coeffStr = mulMatch[1] ?? mulMatch[2];
		const factor = coeffStr === '' ? 1 : coeffStr === '-' ? -1 : parseFloat(coeffStr);
		return factor * Math.PI;
	}

	if (/^-pi$/i.test(s)) return -Math.PI;
	if (/^pi$/i.test(s)) return Math.PI;

	return parseFloat(s);
}
