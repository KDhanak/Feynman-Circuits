import type { CircuitIR, UnitaryOperation, MeasureOperation, ResetOperation, BarrierOperation, CircuitOperation, CanonicalUnitaryGate } from '../IR/schema';
import { isGateId, isParametricGate } from '../quantum/gates';
import { parseAngle } from './openQasmConverter';

export interface QiskitExportOptions {
	includeComments?: boolean;
}

// Variable name for the circuit object in emitted code. Matches IBM Quantum
// Composer's convention (`circuit = ...`) rather than the terser `qc` many
// tutorials use. The importer accepts any variable name, so this is cosmetic.
const CIRCUIT_VAR = 'circuit';

// Qiskit QuantumCircuit method names for controlled gates. Combinations not
// listed here fall back to the append form: circuit.append(XGate().control(n), [...]).
const CONTROLLED_METHOD: Partial<Record<CanonicalUnitaryGate, Record<number, string>>> = {
	x: { 1: 'cx', 2: 'ccx' },
	y: { 1: 'cy' },
	z: { 1: 'cz', 2: 'ccz' },
	h: { 1: 'ch' },
	s: { 1: 'cs' },
	rx: { 1: 'crx' },
	ry: { 1: 'cry' },
	rz: { 1: 'crz' },
	swap: { 1: 'cswap' }
};

// qiskit.circuit.library class per gate, for the append form.
const GATE_CLASS: Record<CanonicalUnitaryGate, string> = {
	x: 'XGate',
	y: 'YGate',
	z: 'ZGate',
	h: 'HGate',
	s: 'SGate',
	t: 'TGate',
	rx: 'RXGate',
	ry: 'RYGate',
	rz: 'RZGate',
	swap: 'SwapGate'
};

export function circuitToQiskit(ir: CircuitIR, options: QiskitExportOptions = {}): string {
	const { includeComments = true } = options;

	// Emit the body first so we know which library classes need importing.
	const usedClasses = new Set<string>();
	const body: string[] = [];

	const sortedOps = [...ir.operations].sort((a, b) => a.column - b.column);
	for (const op of sortedOps) {
		const line = operationToQiskit(op, usedClasses);
		if (line) {
			body.push(line);
		}
	}

	const lines: string[] = [];
	if (includeComments) {
		lines.push('# Generated by Feynman Circuits');
	}
	lines.push('from qiskit import QuantumCircuit');
	if (usedClasses.size > 0) {
		lines.push(`from qiskit.circuit.library import ${[...usedClasses].sort().join(', ')}`);
	}
	lines.push('');

	const numQubits = ir.registers.q;
	const numClassicalBits = ir.registers.c;
	lines.push(numClassicalBits > 0 ? `${CIRCUIT_VAR} = QuantumCircuit(${numQubits}, ${numClassicalBits})` : `${CIRCUIT_VAR} = QuantumCircuit(${numQubits})`);
	lines.push('');
	lines.push(...body);

	return lines.join('\n');
}

function operationToQiskit(op: CircuitOperation, usedClasses: Set<string>): string | null {
	switch (op.kind) {
		case 'unitary':
			return unitaryToQiskit(op as UnitaryOperation, usedClasses);
		case 'measure': {
			const m = op as MeasureOperation;
			return `${CIRCUIT_VAR}.measure(${m.targets[0]}, ${m.classicalTargets[0] ?? 0})`;
		}
		case 'reset':
			return `${CIRCUIT_VAR}.reset(${(op as ResetOperation).targets[0]})`;
		case 'barrier':
			return `${CIRCUIT_VAR}.barrier(${(op as BarrierOperation).targets.join(', ')})`;
		default:
			return null;
	}
}

function unitaryToQiskit(op: UnitaryOperation, usedClasses: Set<string>): string {
	const gate = op.gate;

	if (op.controls.length > 0 || op.antiControls.length > 0) {
		return controlledToQiskit(op, usedClasses);
	}

	if (gate === 'swap') {
		return `${CIRCUIT_VAR}.swap(${op.targets[0]}, ${op.targets[1]})`;
	}
	if (isParametricGate(gate)) {
		const angle = op.params[0] ?? 0;
		return `${CIRCUIT_VAR}.${gate}(${angle}, ${op.targets[0]})`;
	}
	return `${CIRCUIT_VAR}.${gate}(${op.targets[0]})`;
}

// Anti-controls aren't expressible through the named c*/cc* methods, so they're
// implemented via an X-sandwich (same approach as the OpenQASM exporter): flip
// the anti-control qubit, apply the gate with it as a positive control, flip back.
function controlledToQiskit(op: UnitaryOperation, usedClasses: Set<string>): string {
	const gate = op.gate;
	const allControls = [...op.controls, ...op.antiControls];

	if (allControls.length > 2) {
		return `# unsupported: gate "${gate}" with more than 2 controls/anti-controls`;
	}

	const lines: string[] = [];
	for (const ac of op.antiControls) {
		lines.push(`${CIRCUIT_VAR}.x(${ac})`);
	}
	lines.push(controlledInstruction(gate, allControls, op.targets, op.params, usedClasses));
	for (const ac of op.antiControls) {
		lines.push(`${CIRCUIT_VAR}.x(${ac})`);
	}
	return lines.join('\n');
}

function controlledInstruction(
	gate: CanonicalUnitaryGate,
	controls: number[],
	targets: number[],
	params: number[],
	usedClasses: Set<string>
): string {
	const method = CONTROLLED_METHOD[gate]?.[controls.length];
	const qubits = [...controls, ...targets].join(', ');

	if (method) {
		if (isParametricGate(gate)) {
			const angle = params[0] ?? 0;
			return `${CIRCUIT_VAR}.${method}(${angle}, ${qubits})`;
		}
		return `${CIRCUIT_VAR}.${method}(${qubits})`;
	}

	// No named method (e.g. controlled-T, doubly-controlled rotations) — use the
	// generic append form with a library gate class.
	const cls = GATE_CLASS[gate];
	usedClasses.add(cls);
	const ctor = isParametricGate(gate) ? `${cls}(${params[0] ?? 0})` : `${cls}()`;
	return `${CIRCUIT_VAR}.append(${ctor}.control(${controls.length}), [${qubits}])`;
}

// Parse Qiskit Python code back to CircuitIR
export function qiskitToCircuit(pythonCode: string): CircuitIR | null {
	try {
		const lines = pythonCode
			.split('\n')
			.map((l) => l.replace(/#.*$/, '').trim())
			.filter((l) => l.length > 0);

		let numQubits = 0;
		let numClassicalBits = 0;
		let circuitVar: string | null = null;

		// IBM Quantum Composer builds circuits from named register objects
		// (`qreg_q = QuantumRegister(2, 'q')`, then `circuit = QuantumCircuit(qreg_q)`)
		// and addresses qubits as `qreg_q[0]`. Collect those declarations so we can
		// size the circuit and resolve register-indexed args to flat indices.
		const quantumRegs: { name: string; size: number }[] = [];
		const classicalRegs: { name: string; size: number }[] = [];
		for (const line of lines) {
			const qregMatch = line.match(/^(\w+)\s*=\s*QuantumRegister\(\s*(\d+)\s*(?:,\s*['"][^'"]*['"]\s*)?\)/);
			if (qregMatch) {
				quantumRegs.push({ name: qregMatch[1], size: parseInt(qregMatch[2], 10) });
				continue;
			}
			const cregMatch = line.match(/^(\w+)\s*=\s*ClassicalRegister\(\s*(\d+)\s*(?:,\s*['"][^'"]*['"]\s*)?\)/);
			if (cregMatch) {
				classicalRegs.push({ name: cregMatch[1], size: parseInt(cregMatch[2], 10) });
			}
		}

		// Flat offset of each register within its space (quantum vs classical),
		// in declaration order — so a gate on `qreg_b[0]` maps past `qreg_a`'s qubits.
		const offsets = new Map<string, number>();
		let qAcc = 0;
		for (const r of quantumRegs) { offsets.set(r.name, qAcc); qAcc += r.size; }
		let cAcc = 0;
		for (const r of classicalRegs) { offsets.set(r.name, cAcc); cAcc += r.size; }

		const quantumRegSize = new Map(quantumRegs.map((r) => [r.name, r.size]));
		const classicalRegSize = new Map(classicalRegs.map((r) => [r.name, r.size]));

		for (const line of lines) {
			// Integer form: `qc = QuantumCircuit(n)` / `QuantumCircuit(n, m)`.
			// Register form: `circuit = QuantumCircuit(qreg_q)` / `QuantumCircuit(qreg_q, creg_c)`.
			const declMatch = line.match(/^(\w+)\s*=\s*QuantumCircuit\(\s*(.*?)\s*\)/);
			if (declMatch) {
				circuitVar = declMatch[1];
				const args = splitArgs(declMatch[2]);
				if (args.length && args.every((a) => /^\d+$/.test(a))) {
					numQubits = parseInt(args[0], 10);
					numClassicalBits = args[1] ? parseInt(args[1], 10) : 0;
				} else {
					for (const a of args) {
						numQubits += quantumRegSize.get(a) ?? 0;
						numClassicalBits += classicalRegSize.get(a) ?? 0;
					}
				}
				break;
			}
		}

		if (!circuitVar || numQubits === 0) return null;

		const operations: CircuitOperation[] = [];
		// Track the next free column for each qubit so multi-qubit gates
		// don't collide with later single-qubit gates on the same qubit.
		const qubitNextColumn = new Array<number>(numQubits).fill(0);

		const placeOp = (op: CircuitOperation) => {
			const involvedQubits = [
				...(op.targets as number[]),
				...('controls' in op ? (op.controls as number[]) : []),
				...('antiControls' in op ? (op.antiControls as number[]) : [])
			];
			const column = involvedQubits.length
				? Math.max(...involvedQubits.map((q) => qubitNextColumn[q] ?? 0))
				: 0;
			op.column = column;
			for (const q of involvedQubits) {
				qubitNextColumn[q] = column + 1;
			}
			operations.push(op);
		};

		for (const line of lines) {
			const callMatch = line.match(new RegExp(`^${circuitVar}\\.(\\w+)\\s*\\((.*)\\)\\s*$`));
			if (!callMatch) continue;

			const method = callMatch[1];
			const argsStr = callMatch[2];

			if (method === 'measure_all') {
				numClassicalBits = Math.max(numClassicalBits, numQubits);
				for (let q = 0; q < numQubits; q++) {
					placeOp(makeMeasure(q, q));
				}
				continue;
			}

			const parsed = parseMethodCall(method, argsStr, numQubits, offsets);
			if (parsed) {
				placeOp(parsed);
			}
		}

		return {
			version: '1.0',
			registers: { q: numQubits, c: numClassicalBits },
			qubitLabels: Array.from({ length: numQubits }, (_, i) => `q${i}`),
			operations
		};
	} catch {
		return null;
	}
}

function makeUnitary(
	gate: CanonicalUnitaryGate,
	targets: number[],
	controls: number[],
	params: number[]
): UnitaryOperation {
	return {
		id: crypto.randomUUID(),
		kind: 'unitary',
		gate,
		column: 0,
		targets,
		controls,
		antiControls: [],
		params
	};
}

function makeMeasure(qubit: number, classicalBit: number): MeasureOperation {
	return {
		id: crypto.randomUUID(),
		kind: 'measure',
		gate: 'measure',
		column: 0,
		targets: [qubit],
		classicalTargets: [classicalBit]
	};
}

function parseMethodCall(
	method: string,
	argsStr: string,
	numQubits: number,
	offsets: Map<string, number>
): CircuitOperation | null {
	const args = splitArgs(argsStr);
	const idxOf = (arg: string) => parseIndex(arg, offsets);

	// circuit.append(TGate().control(1), [0, 1]) / append(RXGate(pi/2).control(2), [0, 1, 2])
	if (method === 'append') {
		return parseAppendCall(argsStr, offsets);
	}

	if (method === 'measure' && args.length === 2) {
		const q = idxOf(args[0]);
		const c = idxOf(args[1]);
		if (q === null || c === null) return null;
		return makeMeasure(q, c);
	}

	if (method === 'reset' && args.length === 1) {
		const q = idxOf(args[0]);
		if (q === null) return null;
		return {
			id: crypto.randomUUID(),
			kind: 'reset',
			gate: 'reset',
			column: 0,
			targets: [q]
		};
	}

	if (method === 'barrier') {
		const qubits = args.length
			? args.map(idxOf).filter((q): q is number => q !== null)
			: Array.from({ length: numQubits }, (_, i) => i);
		return {
			id: crypto.randomUUID(),
			kind: 'barrier',
			gate: 'barrier',
			column: 0,
			targets: qubits
		};
	}

	if (method === 'swap' && args.length === 2) {
		const t0 = idxOf(args[0]);
		const t1 = idxOf(args[1]);
		if (t0 === null || t1 === null) return null;
		return makeUnitary('swap', [t0, t1], [], []);
	}

	if (method === 'cswap' && args.length === 3) {
		const idx = args.map(idxOf);
		if (idx.some((v) => v === null)) return null;
		return makeUnitary('swap', [idx[1]!, idx[2]!], [idx[0]!], []);
	}

	// Controlled rotations: crx(theta, c, t)
	const crotMatch = method.match(/^c(rx|ry|rz)$/);
	if (crotMatch && args.length === 3) {
		const angle = parsePythonAngle(args[0]);
		const control = idxOf(args[1]);
		const target = idxOf(args[2]);
		if (angle === null || control === null || target === null) return null;
		return makeUnitary(crotMatch[1] as CanonicalUnitaryGate, [target], [control], [angle]);
	}

	// Doubly-controlled: ccx(c1, c2, t), ccz(c1, c2, t)
	const ccMatch = method.match(/^cc([xz])$/);
	if (ccMatch && args.length === 3) {
		const idx = args.map(idxOf);
		if (idx.some((v) => v === null)) return null;
		return makeUnitary(ccMatch[1] as CanonicalUnitaryGate, [idx[2]!], [idx[0]!, idx[1]!], []);
	}

	// Singly-controlled: cx(c, t), cy, cz, ch, cs
	const cMatch = method.match(/^c([xyzhs])$/);
	if (cMatch && args.length === 2) {
		const control = idxOf(args[0]);
		const target = idxOf(args[1]);
		if (control === null || target === null) return null;
		return makeUnitary(cMatch[1] as CanonicalUnitaryGate, [target], [control], []);
	}

	// Rotations: rx(theta, t)
	if (isGateId(method) && isParametricGate(method) && args.length === 2) {
		const angle = parsePythonAngle(args[0]);
		const target = idxOf(args[1]);
		if (angle === null || target === null) return null;
		return makeUnitary(method, [target], [], [angle]);
	}

	// Plain single-qubit gates: x(t), y, z, h, s, t
	if (isGateId(method) && !isParametricGate(method) && args.length === 1) {
		const target = idxOf(args[0]);
		if (target === null) return null;
		return makeUnitary(method, [target], [], []);
	}

	return null;
}

// circuit.append(<Class>(<params?>).control(<n>), [<qubits>])
function parseAppendCall(argsStr: string, offsets: Map<string, number>): CircuitOperation | null {
	const match = argsStr.match(/^(\w+)\(([^)]*)\)\.control\(\s*(\d+)\s*\)\s*,\s*\[([^\]]+)\]$/);
	if (!match) return null;

	const className = match[1];
	const gate = (Object.entries(GATE_CLASS).find(([, cls]) => cls === className)?.[0] ?? null) as CanonicalUnitaryGate | null;
	if (!gate) return null;

	const numControls = parseInt(match[3], 10);
	const qubits = splitArgs(match[4]).map((a) => parseIndex(a, offsets));
	if (qubits.some((v) => v === null)) return null;

	const controls = (qubits as number[]).slice(0, numControls);
	const targets = (qubits as number[]).slice(numControls);
	if (targets.length === 0) return null;

	const params: number[] = [];
	if (isParametricGate(gate)) {
		const angle = parsePythonAngle(match[2]);
		if (angle === null) return null;
		params.push(angle);
	}

	return makeUnitary(gate, targets, controls, params);
}

function splitArgs(argsStr: string): string[] {
	const trimmed = argsStr.trim();
	if (!trimmed) return [];
	return trimmed.split(',').map((a) => a.trim());
}

// Resolves a qubit/clbit argument to a flat index. Accepts a bare integer
// (`0`) or a register-indexed reference (`qreg_q[0]`), mapping the latter to
// its flat position via the register's offset.
function parseIndex(arg: string, offsets: Map<string, number>): number | null {
	if (/^\d+$/.test(arg)) return parseInt(arg, 10);
	const regMatch = arg.match(/^(\w+)\[\s*(\d+)\s*\]$/);
	if (regMatch) {
		const base = offsets.get(regMatch[1]) ?? 0;
		return base + parseInt(regMatch[2], 10);
	}
	return null;
}

// Accepts plain numbers plus pi expressions with optional numpy/math prefixes:
// pi/2, np.pi/2, math.pi, 2*pi, -pi/4, ...
function parsePythonAngle(arg: string): number | null {
	const normalized = arg.replace(/\b(?:np|numpy|math)\./g, '').trim();
	const value = parseAngle(normalized);
	return Number.isFinite(value) ? value : null;
}
